// Helper to format Korean currency in readable terms
export function formatKoreanMoney(amount: number): string {
  if (amount === 0) return "0원";
  
  const gyeong = Math.floor(amount / 10_000_000_000_000_000);
  const jo = Math.floor((amount % 10_000_000_000_000_000) / 1_000_000_000_000);
  const eok = Math.floor((amount % 1_000_000_000_000) / 100_000_000);
  const man = Math.floor((amount % 100_000_000) / 10_000);
  const won = Math.floor(amount % 10_000);

  const parts: string[] = [];
  if (gyeong > 0) parts.push(`${gyeong.toLocaleString()}경`);
  if (jo > 0) parts.push(`${jo.toLocaleString()}조`);
  if (eok > 0) parts.push(`${eok.toLocaleString()}억`);
  if (man > 0 && gyeong === 0) parts.push(`${man.toLocaleString()}만`);
  if (won > 0 && gyeong === 0 && jo === 0 && eok === 0) parts.push(`${won.toLocaleString()}`);

  return parts.length > 0 ? `${parts.join(' ')} 원` : `${amount.toLocaleString()} 원`;
}

